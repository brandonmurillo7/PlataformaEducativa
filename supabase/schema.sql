  on public.estudiantes for all to authenticated using (true) with check (true);
create policy "authenticated users can manage subjects"
  on public.asignaturas for all to authenticated using (true) with check (true);
create policy "authenticated users can manage grades"
  on public.calificaciones for all to authenticated using (true) with check (true);
create policy "authenticated users can manage tasks"
  on public.tareas for all to authenticated using (true) with check (true);
create policy "authenticated users can manage tutoring"
  on public.tutorias for all to authenticated using (true) with check (true);
create policy "authenticated users can manage student connections"
  on public.conexiones_estudiantes for all to authenticated using (true) with check (true);
